"""Research-cycle orchestrator.

The Orchestrator coordinates a research cycle:

    plan -> delegate -> investigate -> report -> review -> synthesize -> commit -> reassess

It is intentionally dependency-free (Python standard library only) so it can be
run immediately.  A future version may replace the hand-rolled state machine
with LangGraph (see docs/02-technology/frameworks.md) to gain checkpoints and
native human-in-the-loop interrupts.
"""

from __future__ import annotations

from pathlib import Path
from typing import Optional

from .state import ResearchState
from .worktree_manager import WorktreeManager


class Orchestrator:
    """Manages one Atlas research cycle."""

    def __init__(
        self,
        repo_root: Path | str,
        worktree_parent: Path | str,
        knowledge_base: Path | str,
    ) -> None:
        self.repo_root = Path(repo_root).resolve()
        self.worktree_parent = Path(worktree_parent).resolve()
        self.knowledge_base = Path(knowledge_base).resolve()
        self.worktree_manager = WorktreeManager(self.repo_root, self.worktree_parent)

    # ------------------------------------------------------------------
    # Public entry point
    # ------------------------------------------------------------------
    def run_cycle(self, objective: str, domains: list[str]) -> ResearchState:
        """Execute one full research cycle and return the final state."""
        state = ResearchState(objective=objective, domains=list(domains))
        state.current_phase = "plan"
        state.log(f"Starting cycle for objective: {objective}")

        self._plan(state)
        self._delegate(state)
        self._investigate(state)
        self._report(state)
        self._synthesize(state)
        self._review(state)

        state.current_phase = "reassess"
        state.log("Cycle complete")
        return state

    # ------------------------------------------------------------------
    # Cycle phases
    # ------------------------------------------------------------------
    def _plan(self, state: ResearchState) -> None:
        """Decompose the objective into independent research domains."""
        if not state.domains:
            raise ValueError("No domains provided for planning")
        state.log(f"Plan: {len(state.domains)} domains -> {state.domains}")
        state.current_phase = "delegate"

    def _delegate(self, state: ResearchState) -> None:
        """Create a Git branch and worktree for each domain."""
        current = self.worktree_manager.current_branch()
        if current != "main":
            raise RuntimeError(f"Must run from main branch, currently on {current!r}")

        for domain in state.domains:
            branch = f"research/{domain}"
            if not self.worktree_manager.branch_exists(branch):
                self.worktree_manager.create_branch(branch)
            worktree_path = self.worktree_manager.create_worktree(domain, branch)
            state.worktrees[domain] = str(worktree_path)
            state.log(f"Delegate: {domain} -> branch {branch}, worktree {worktree_path}")
        state.current_phase = "investigate"

    def _investigate(self, state: ResearchState) -> None:
        """Placeholder for worker investigation.

        In the full system, a worker agent executes research inside each
        worktree and writes a report file.  Here we create a placeholder
        report so the cycle can proceed end-to-end.
        """
        for domain, worktree_path in state.worktrees.items():
            wt = Path(worktree_path)
            report_path = wt / "docs" / "research" / domain / "REPORT.md"
            report_path.parent.mkdir(parents=True, exist_ok=True)
            report_path.write_text(
                f"# Research Report — {domain}\n\n"
                f"Objective: {state.objective}\n\n"
                "## Findings\n\n"
                "Placeholder report generated by the orchestrator.\n"
                "Replace with actual agent research.\n"
            )
            state.reports[domain] = str(report_path)
            state.log(f"Investigate: {domain} -> report at {report_path}")
        state.current_phase = "report"

    def _report(self, state: ResearchState) -> None:
        """Collect worker reports (already stored during investigate)."""
        state.log(f"Report: collected {len(state.reports)} reports")
        state.current_phase = "review"

    def _synthesize(self, state: ResearchState) -> None:
        """Combine reports into a synthesis placeholder."""
        lines = [f"# Synthesis — {state.objective}", ""]
        for domain in state.domains:
            lines.append(f"## {domain}")
            lines.append(f"Report: {state.reports.get(domain, 'missing')}")
            lines.append("")
        self.knowledge_base.mkdir(parents=True, exist_ok=True)
        synthesis_path = self.knowledge_base / "cycle-synthesis.md"
        synthesis_path.write_text("\n".join(lines))
        state.synthesis = str(synthesis_path)
        state.log(f"Synthesize: wrote {synthesis_path}")
        state.current_phase = "commit"

    def _review(self, state: ResearchState) -> None:
        """Human-in-the-loop review gate.

        In production this is a LangGraph interrupt where the Manager Agent
        APPROVEs, requests REVISION, or REJECTs.  Here we mark the state as
        pending review and print instructions for the Manager Agent.
        """
        state.review_status = "pending"
        state.current_phase = "review"
        print("\n=== REVIEW GATE ===")
        print(state.summary())
        print("\nManager Agent: review the synthesis and set review_status to")
        print("  'approved', 'revision_required', or 'rejected'.")
        print("=================\n")

    def commit_approved(self, state: ResearchState) -> None:
        """Merge an approved branch into main (Manager Agent only).

        Call this only after the Manager Agent has set review_status to
        ``approved``.  Merges each domain branch into main and removes its
        worktree.
        """
        if state.review_status != "approved":
            raise RuntimeError(f"Cannot commit: review_status is {state.review_status!r}")

        for domain, branch in ((d, f"research/{d}") for d in state.domains):
            self.worktree_manager._run(["merge", "--no-ff", branch, "-m", f"docs: integrate {domain}"])
            state.log(f"Commit: merged {branch} into main")
        state.current_phase = "reassess"
        state.log("Commit: all approved branches merged")
